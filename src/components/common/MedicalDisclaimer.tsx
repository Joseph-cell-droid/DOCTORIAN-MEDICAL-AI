/**
 * Doctorian Clinical Intelligence - Medical Disclaimer Component
 * Provides clean, multi-variant disclaimers to ensure safe AI clinical interactions:
 * - "inline": Subtle, non-intrusive disclaimer placed beneath AI responses
 * - "banner": High-visibility cautionary banner with emergency guidance
 * - "compact": Sleek single-line badge with expandable info for mobile/chat views
 */

import React, { useState } from 'react';
import { AlertTriangle, ShieldAlert, Info, ChevronDown, ChevronUp, Stethoscope } from 'lucide-react';

export interface MedicalDisclaimerProps {
  variant?: 'inline' | 'banner' | 'compact';
  className?: string;
  showEmergencyNotice?: boolean;
}

export const MedicalDisclaimer: React.FC<MedicalDisclaimerProps> = ({
  variant = 'inline',
  className = '',
  showEmergencyNotice = false
}) => {
  const [isExpanded, setIsExpanded] = useState(false);

  // Compact variant for dense mobile views and message bubbles
  if (variant === 'compact') {
    return (
      <div className={`text-[10px] text-slate-500 dark:text-slate-400 border border-slate-200/60 dark:border-slate-800/80 rounded-lg p-2 bg-slate-50/70 dark:bg-slate-900/60 ${className}`}>
        <div className="flex items-center justify-between gap-1.5 cursor-pointer" onClick={() => setIsExpanded(!isExpanded)}>
          <div className="flex items-center gap-1.5 font-medium">
            <ShieldAlert size={12} className="text-amber-500 shrink-0" />
            <span className="truncate">Clinical decision-support tool. Not a substitute for a licensed clinician.</span>
          </div>
          <button
            type="button"
            className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 transition-colors p-0.5"
            aria-label="Toggle disclaimer details"
          >
            {isExpanded ? <ChevronUp size={12} /> : <ChevronDown size={12} />}
          </button>
        </div>

        {isExpanded && (
          <p className="mt-1.5 text-[10px] text-slate-500 dark:text-slate-400 leading-relaxed border-t border-slate-200/50 dark:border-slate-800/50 pt-1.5">
            Doctorian Medical AI provides informational insights aligned with WHO and Uganda Clinical Guidelines. Always verify findings with a certified medical doctor before taking medication or altering clinical therapy.
          </p>
        )}
      </div>
    );
  }

  // High-visibility banner variant
  if (variant === 'banner') {
    return (
      <aside
        role="note"
        aria-label="Medical Disclaimer Banner"
        className={`w-full rounded-2xl bg-amber-50/90 dark:bg-amber-950/30 border border-amber-200/80 dark:border-amber-800/60 p-3 sm:p-4 text-amber-900 dark:text-amber-200 shadow-2xs ${className}`}
      >
        <div className="flex items-start gap-3">
          <div className="w-8 h-8 rounded-xl bg-amber-500/10 dark:bg-amber-500/20 text-amber-600 dark:text-amber-400 flex items-center justify-center shrink-0 mt-0.5">
            <AlertTriangle size={18} />
          </div>
          <div className="space-y-1 text-xs">
            <h4 className="font-black uppercase tracking-wider text-[11px] text-amber-800 dark:text-amber-300 flex items-center gap-1.5">
              <span>Clinical Disclaimer &amp; Patient Safety Notice</span>
            </h4>
            <p className="leading-relaxed text-amber-900/90 dark:text-amber-200/90">
              This application is an artificial intelligence support tool. It does <strong>not</strong> establish a doctor-patient relationship, render binding clinical diagnoses, or prescribe regulated medications.
            </p>
            {showEmergencyNotice && (
              <p className="font-bold text-rose-700 dark:text-rose-400 text-[11px] pt-1">
                🚨 If you are experiencing chest pain, severe shortness of breath, loss of consciousness, or uncontrollable bleeding, proceed immediately to the nearest hospital emergency department or call emergency services.
              </p>
            )}
          </div>
        </div>
      </aside>
    );
  }

  // Default: inline variant (placed neatly below AI outputs)
  return (
    <div
      role="note"
      className={`mt-3 pt-2.5 border-t border-slate-200/70 dark:border-slate-800 text-[11px] text-slate-500 dark:text-slate-400 flex items-start gap-2 bg-slate-50/50 dark:bg-slate-900/30 p-2.5 rounded-xl ${className}`}
    >
      <Stethoscope size={14} className="text-blue-500 dark:text-blue-400 shrink-0 mt-0.5" />
      <div className="leading-normal">
        <strong className="text-slate-700 dark:text-slate-300 font-bold">Medical Disclaimer: </strong>
        <span>
          This output is generated by Doctorian AI as clinical support and informational reference based on WHO and Uganda Clinical Guidelines. It is <strong>not a medical diagnosis</strong>. Please consult a qualified healthcare professional for personalized clinical evaluation.
        </span>
      </div>
    </div>
  );
};

export default MedicalDisclaimer;
